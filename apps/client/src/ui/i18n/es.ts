const plural: Record<Card | 'gray', string> = {
  red: 'rojas',
  orange: 'naranjas',
  yellow: 'amarillas',
  green: 'verdes',
  blue: 'azules',
  purple: 'rosas',
  black: 'negras',
  white: 'blancas',
  locomotive: 'locomotoras',
  excavator: 'excavadoras',
  gray: 'de un solo color',
};
const lc = (c: Card | 'gray') => cards[c].toLowerCase();
/** "una carta roja" / "una locomotora" */
const aCard = (c: Card) => (c === 'locomotive' || c === 'excavator' ? `una ${lc(c)}` : `una carta ${lc(c)}`);
const colorPlural = (c: string) => plural[c as Card] ?? c;

